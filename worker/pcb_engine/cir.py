"""SPICE netlist (.cir) transformation.

Strategy (plan T-401):
  * Whole-net extraction — replace every reference to the target net with
    `<net>__PAR`, then rebuild the original net as
        <net> -- R_PAR -- mid -- L_PAR -- <net>__PAR
    with a shunt C_PAR from the SOURCE side to the reference node.
  * Non-destructive: the original text is never edited in place; we return a
    complete new document + unified diff. Idempotency via a marker comment.
  * Only token-exact node matches are rewritten; lines starting with '*' and
    dot-commands (except missing `.include`) are untouched.
"""
from __future__ import annotations

import difflib
import re

MARKER = "* — PCB parasitic network (auto-generated by pcb-parasitic-qspice) — do not hand-edit"
LIB_NAME = "parasitics.lib"

_NAME_SAFE = re.compile(r"[^0-9A-Za-z_]")


def sanitize_net(name: str) -> str:
    n = _NAME_SAFE.sub("_", name.strip())
    if n and n[0].isdigit():
        n = "N_" + n
    return n or "NET"


def is_injected(text: str) -> bool:
    return any(line.strip() == MARKER for line in text.splitlines())


def _sanitize_token(tok: str) -> str:
    return tok.strip()


def _rewrite_line(line_idx: int, line: str, lower_map: dict[str, str],
                  anchors: set[str]) -> str:
    """Rewrite node tokens, case-insensitively (SPICE is case-insensitive).

    `anchors` = lower-cased net names whose ORIGINAL spelling must survive on
    THIS line (it is an independent source or the first referencing device —
    the ladder boundary). Everything else is re-pointed at `<SAN>__PAR`.
    """
    stripped = line.strip()
    if not stripped or stripped.startswith("*"):
        return line
    if stripped.startswith("."):
        return line  # dot-commands untouched (e.g. .include added exactly once elsewhere)
    parts = line.split()
    out = []
    for tok in parts:
        if "=" in tok or tok.lower().startswith(("{", "'")):
            out.append(tok)
            continue
        bare = tok.strip('"')
        hit = lower_map.get(bare.lower())
        if hit is None or bare.lower() in anchors:
            out.append(tok)
        else:
            out.append(hit)
    return " ".join(out)


def _word_ref(line: str, net_lower: str) -> bool:
    return re.search(r"(?<![A-Za-z0-9_])" + re.escape(net_lower) + r"(?![A-Za-z0-9_])",
                     line.lower()) is not None


# Independent SPICE sources (name starts with V/I) are treated as the natural
# boundary for power nets: the source keeps the original node, everything else
# is re-pointed. For nets without an independent source (e.g. switching nodes),
# the FIRST referencing device line anchors the boundary — in a commutation
# loop the position of the lumped cut does not change the first-order resonance.
_INDEP_SRC = re.compile(r"^[VvIi]")


def _boundary_lines(lines: list[str], nets_lower: list[str]) -> dict[str, set[int]]:
    """net(lower) -> line indices whose tokens stay on the ORIGINAL side of its ladder.

    Independent SPICE sources (name starts with V/I) are the natural boundary
    for power nets: the source keeps the original node, everything else moves.
    Nets without an independent source (e.g. switching nodes) anchor at their
    first referencing device — in a commutation loop the position of the
    lumped cut does not change the first-order resonance.
    """
    anchors: dict[str, set[int]] = {}
    for nl in nets_lower:
        idxs = [i for i, ln in enumerate(lines)
                if ln.strip() and not ln.strip().startswith(("*", ".")) and _word_ref(ln, nl)]
        src_lines = [i for i in idxs if _INDEP_SRC.match((lines[i].split() or [""])[0])]
        anchors[nl] = set(src_lines) if src_lines else set(idxs[:1])
    return anchors


def transform(text: str, parasitics: dict, ref_node: str = "0") -> tuple[str, str, dict]:
    """Returns (new_text, unified_diff, stats).

    `parasitics` = {nodes:
        [{name, r_ohm, l_h, c_f}, ...]}
    """
    if is_injected(text):
        raise ValueError("netlist already contains a pcb-parasitic-qspice block — refusing to double-inject")

    targets = parasitics["nets"]
    if not targets:
        raise ValueError("no target nets selected")

    net_map = {t["name"]: sanitize_net(t["name"]) + "__PAR" for t in targets}
    lower_map = {k.lower(): v for k, v in net_map.items()}

    lines = text.splitlines()
    boundary = _boundary_lines(lines, list(lower_map))
    rewritten = []
    for i, ln in enumerate(lines):
        anchors = {nl for nl, idxs in boundary.items() if i in idxs}
        rewritten.append(_rewrite_line(i, ln, lower_map, anchors))

    # insertion index = line of last `.end` (case-insensitive); else end of file
    end_idx = None
    for i, ln in enumerate(rewritten):
        if ln.strip().lower() == ".end":
            end_idx = i
    if end_idx is None:
        rewritten.append(".end")
        end_idx = len(rewritten) - 1

    elems: list[str] = [MARKER,
                        f".include {LIB_NAME}",
                        f"* reference node for shunt elements: {ref_node}"]
    n_r = n_l = n_c = n_k = 0
    prov: list[str] = []
    for i, t in enumerate(targets):
        n = sanitize_net(t["name"])
        r, l_h, c_f = t["r_ohm"], t["l_h"], t["c_f"]
        mid = f"{n}_MIDPAR{i}"
        elems.append(f"R_PAR_{n} {n} {mid} {r:.6g}")
        elems.append(f"L_PAR_{n} {mid} {n}__PAR {l_h:.6e}")
        elems.append(f"C_PAR_{n} {n} {ref_node} {c_f:.6e}")
        n_r += 1; n_l += 1; n_c += 1
        prov.append(f"* {t['name']}: R={r:.4g} ohm, L={l_h*1e9:.4g} nH, C={c_f*1e12:.4g} pF "
                    f"@ {t.get('f0_hz', 1e6):,.0f} Hz — {t.get('method', 'Tier A')}")
    elems.extend(prov)

    # mutual-inductance coupling (only when PEEC Tier B provides values)
    for i, pair in enumerate(parasitics.get("mutuals", [])):
        a = sanitize_net(pair["a"]); b = sanitize_net(pair["b"])
        elems.append(f"K_PAR_{i} L_PAR_{a} L_PAR_{b} {pair['k']:.4g}")
        n_k += 1

    body, tail = rewritten[:end_idx], rewritten[end_idx:]
    new_lines = body + [""] + elems + [""] + tail
    new_text = "\n".join(new_lines)
    if not new_text.endswith("\n"):
        new_text += "\n"

    diff = "".join(difflib.unified_diff(text.splitlines(keepends=True),
                                        new_text.splitlines(keepends=True),
                                        fromfile="original.cir", tofile="injected.cir", n=2))
    stats = {"lines_before": len(lines), "lines_after": len(new_lines),
             "nets": len(targets), "elements_added": n_r + n_l + n_c + n_k,
             "r_added": n_r, "l_added": n_l, "c_added": n_c, "k_added": n_k,
             "net_map": net_map}
    return new_text, diff, stats


def generate_library(parasitics: dict, ref_node: str = "0") -> str:
    """stand-alone parasitics.lib with provenance (imported with .include)."""
    lines = [
        "* parasitics.lib — auto-generated by pcb-parasitic-qspice",
        "* DO NOT EDIT — regenerate from your PCB after layout changes",
        f"* reference node: {ref_node}",
        f"* network type: whole-net PI network (see README §injection)",
        "",
    ]
    for t in parasitics["nets"]:
        n = sanitize_net(t["name"])
        lines.append(f"* ---- net {t['name']} ----")
        lines.append(f"* R={t['r_ohm']:.6g} ohm  L={t['l_h']:.6e} H  C={t['c_f']:.6e} F")
        lines.append(f"* method: {t.get('method', 'Tier A closed-form')} — "
                     f"uncertainty {t.get('uncertainty', '±5–10 %')}")
    lines.append("")
    return "\n".join(lines) + "\n"
